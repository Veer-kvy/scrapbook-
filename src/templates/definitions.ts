function look(base: PageStyle, patch: Partial<PageStyle> = {}): PageStyle {
  return { ...base, ...patch };
}

const SOFT: PageStyle = {
  accent: '#C98C9D',
  tint: 'none',
  border: 'none',
  shadow: 'soft',
  entrance: 'rise',
  hover: 'lift',
  decor: true,
};

function templatePage(
  id: TemplateId,
  style: PageStyle,
  elements: ScrapbookElement[],
  transition: PageTransitionId = 'turn',
): Page {
  return {
    id: uid('page-'),
    name: TEMPLATE_LABELS[id],
    template: id,
    bg: TEMPLATE_BG[id],
    transition,
    style,
    elements,
  };
}

/** Photo slots start empty so the club member chooses the photograph later. */
function photoSlot(opts: Parameters<typeof makePhoto>[1]) {
  return makePhoto('', opts);
}

